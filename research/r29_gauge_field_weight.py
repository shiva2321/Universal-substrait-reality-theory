def dual_scalar_2d(l, L):
    k = 2 * np.pi * (np.arange(L) + 0.5) / L
    KX, KY = np.meshgrid(k, k, indexing="ij")
    om = np.sqrt(4 * (np.sin(KX / 2) ** 2 + np.sin(KY / 2) ** 2))
    gphi, gpi = np.fft.ifft2(1 / (2 * om)), np.fft.ifft2(om / 2)

    def corr(g, A, B):
        A, B = np.array(A), np.array(B)
        dlt = A[:, None, :] - B[None, :, :]
        return np.real(g[(dlt[..., 0] % L, dlt[..., 1] % L)] * np.exp(1j * np.pi * dlt.sum(-1) / L))

    D = [(x, y) for x in range(l - 1) for y in range(l - 1)]
    Q = [(x, y) for x in range(-1, l) for y in range(-1, l) if not (0 <= x <= l - 2 and 0 <= y <= l - 2)]
    q0, Qr = Q[0], Q[1:]
    allp = D + Qr + [q0]
    C = corr(gphi, allp, allp)
    nD, nQ = len(D), len(Qr)
    T = np.zeros((nD + nQ, nD + nQ + 1))
    for n in range(nD + nQ):
        T[n, n], T[n, -1] = 1, -1                                  # X_p = phi_p - phi_q0, Y_q = phi_q - phi_q0
    GG = T @ C @ T.T
    GXX, GXY, GYY = GG[:nD, :nD], GG[:nD, nD:], GG[nD:, nD:]
    Gcond = GXX - GXY @ np.linalg.solve(GYY, GXY.T)
    Gpp = corr(gpi, D, D)
    nu = np.sqrt(np.clip(np.linalg.eigvals(Gcond @ Gpp).real, 0, None))
    return sym_entropy(nu), 0.5 * np.linalg.slogdet(2 * np.pi * np.e * GYY)[1]


def area_fit(ells, S, lo=4, logterm=False):
    ells = np.asarray(ells, float)
    S = np.asarray(S)
    sel = ells >= lo
    cols = [6 * ells[sel] ** 2, ells[sel]] + ([np.log(ells[sel])] if logterm else []) + [np.ones(sel.sum())]
    return np.linalg.lstsq(np.vstack(cols).T, S[sel], rcond=None)[0]


