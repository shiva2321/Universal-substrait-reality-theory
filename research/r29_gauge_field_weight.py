def momentum_grid(L, d):
    k1 = 2 * np.pi * (np.arange(L) + 0.5) / L
    return np.meshgrid(*([k1] * d), indexing="ij")


def maxwell_tables(L, d):
    """ifft'ed real-space tables of <E_i E_j>, <B B>; and the Coulomb-gauge <A_i A_j> (for the naive comparison).
    d_i = e^{ik_i} - 1, K^2 = sum |d_i|^2 = omega^2, P_ij = delta_ij - d_i d_j^* / K^2."""
    ks = momentum_grid(L, d)
    dd = [np.exp(1j * k) - 1 for k in ks]
    om = np.sqrt(sum(abs(x) ** 2 for x in dd))
    K2 = om ** 2
    gE, gA = {}, {}
    for i in range(d):
        for j in range(d):
            P = (1.0 if i == j else 0.0) - dd[i] * np.conj(dd[j]) / K2
            gE[(i, j)] = np.fft.ifftn(0.5 * om * P)
            gA[(i, j)] = np.fft.ifftn(P / (2 * om))
    pairs = [(b, c) for b in range(d) for c in range(b + 1, d)]

    def mrow(bc):                     # B_{bc} = d_b A_c - d_c A_b
        b, c = bc
        row = [np.zeros_like(K2, dtype=complex) for _ in range(d)]
        row[c] = row[c] + dd[b]
        row[b] = row[b] - dd[c]
        return row

    gB = {}
    for p1 in pairs:
        r1 = mrow(p1)
        for p2 in pairs:
            r2 = mrow(p2)
            gB[(p1, p2)] = np.fft.ifftn(sum(r1[e] * np.conj(r2[e]) for e in range(d)) / (2 * om))
    return gE, gB, gA, pairs


def lookup(g, L, X1, X2):
    dlt = X1[:, None, :] - X2[None, :, :]
    idx = tuple(dlt[..., a] % L for a in range(dlt.shape[-1]))
    return g[idx] * np.exp(1j * np.pi * dlt.sum(-1) / L)


def build_region(l, d):
    C = set(itertools.product(range(l), repeat=d))
    links_in, links_bd = [], []
    for x in itertools.product(range(-1, l), repeat=d):
        for i in range(d):
            y = list(x)
            y[i] += 1
            xin, yin = x in C, tuple(y) in C
            if xin and yin:
                links_in.append((x, i))
            elif xin or yin:
                links_bd.append((x, i))
    plaqs = []
    for x in C:
        for b in range(d):
            for c in range(b + 1, d):
                xb, xc = list(x), list(x)
                xb[b] += 1
                xc[c] += 1
                xbc = list(xb)
                xbc[c] += 1
                if tuple(xb) in C and tuple(xc) in C and tuple(xbc) in C:
                    plaqs.append((x, (b, c)))
    return links_in, links_bd, plaqs


def incidence(links_in, plaqs):
    lid = {lk: n for n, lk in enumerate(links_in)}
    Cm = np.zeros((len(links_in), len(plaqs)))
    for pn, (x, (b, c)) in enumerate(plaqs):
        xb, xc = list(x), list(x)
        xb[b] += 1
        xc[c] += 1
        Cm[lid[(tuple(xb), c)], pn] += 1          # B_bc(x) = A_c(x+b) - A_c(x) - A_b(x+c) + A_b(x)
        Cm[lid[(x, c)], pn] -= 1
        Cm[lid[(tuple(xc), b)], pn] -= 1
        Cm[lid[(x, b)], pn] += 1
    return Cm


def sym_entropy(nu):
    nu = nu[nu > 0.5 + 1e-10]
    return float(np.sum((nu + 0.5) * np.log(nu + 0.5) - (nu - 0.5) * np.log(nu - 0.5)))


def link_block(tab, L, X, I, d):
    n = len(X)
    out = np.zeros((n, n))
    for i in range(d):
        ii = np.nonzero(I == i)[0]
        for j in range(d):
            jj = np.nonzero(I == j)[0]
            if len(ii) and len(jj):
                out[np.ix_(ii, jj)] = lookup(tab[(i, j)], L, X[ii], X[jj]).real
    return 0.5 * (out + out.T)


def gauge_cube(l, L, d, tabs, checks=False):
    """Electric-centre entropy of a cube: returns S_sym, S_cl (flux quantum 1), number of classical modes, info."""
    gE, gB, gA, pairs = tabs
    links_in, links_bd, plaqs = build_region(l, d)
    nin, nbd, nB = len(links_in), len(links_bd), len(plaqs)
    allE = links_in + links_bd
    X = np.array([lk[0] for lk in allE])
    I = np.array([lk[1] for lk in allE])
    GE = link_block(gE, L, X, I, d)
    XB = np.array([pl[0] for pl in plaqs]).reshape(-1, d)
    TB = [pl[1] for pl in plaqs]
    GB = np.zeros((nB, nB))
    for p1 in pairs:
        ii = np.array([n for n, t in enumerate(TB) if t == p1], dtype=int)
        for p2 in pairs:
            jj = np.array([n for n, t in enumerate(TB) if t == p2], dtype=int)
            if len(ii) and len(jj):
                GB[np.ix_(ii, jj)] = lookup(gB[(p1, p2)], L, XB[ii], XB[jj]).real
    GB = 0.5 * (GB + GB.T)
    Cinc = incidence(links_in, plaqs)
    Gin, Gib, Gbb = GE[:nin, :nin], GE[:nin, nin:], GE[nin:, nin:]
    # classical part: n-1 independent integer-valued boundary fluxes (drop the last link; the Gauss constraint
    # sum_out E - sum_in E = 0 has unit coefficients, so the rest generate the integer lattice)
    Gsub = Gbb[:-1, :-1]
    S_cl = 0.5 * np.linalg.slogdet(2 * np.pi * np.e * Gsub)[1]
    # conditioning of the quantum part on the classical fluxes
    w, V = np.linalg.eigh(Gbb)
    keep = w > 1e-10 * w.max()
    Gcond = Gin - Gib @ ((V[:, keep] / w[keep]) @ V[:, keep].T) @ Gib.T
    U, S, Vt = np.linalg.svd(Cinc, full_matrices=True)
    r = int((S > 1e-9).sum())
    Ur, Vr = U[:, :r], Vt[:r].T
    GQQ = Ur.T @ Gcond @ Ur
    GPP = (Vr.T @ GB @ Vr) / np.outer(S[:r], S[:r])
    Lq = np.linalg.cholesky(0.5 * (GQQ + GQQ.T) + 1e-14 * np.eye(r))
    nu2 = np.linalg.eigvalsh(Lq.T @ GPP @ Lq)
    nu = np.sqrt(np.clip(nu2, 0, None))
    info = {"nin": nin, "nbd": nbd, "nB": nB, "r": r, "numin": float(nu.min()), "numax": float(nu.max())}
    if checks:
        wE = np.linalg.eigvalsh(GE)
        wB = np.linalg.eigvalsh(GB)
        info.update(rankE=int((wE > 1e-10 * wE.max()).sum()), rankB=int((wB > 1e-10 * wB.max()).sum()),
                    null_in=float(abs(U[:, r:].T @ Gcond @ U[:, r:]).max()) if U.shape[1] > r else 0.0,
                    null_B=float(abs(Vt[r:] @ GB @ Vt[r:].T).max()) if Vt.shape[0] > r else 0.0)
    return sym_entropy(nu), float(S_cl), nbd - 1, info


def coulomb_cube(l, L, d, tabs, include_bd):
    """Naive entropy of the Coulomb-gauge link variables (A_l^T, E_l^T): NOT gauge invariant; this is the
    quantity behind the claim 'two polarizations = two scalars'."""
    gE, gB, gA, pairs = tabs
    links_in, links_bd, _ = build_region(l, d)
    links = links_in + (links_bd if include_bd else [])
    X = np.array([lk[0] for lk in links])
    I = np.array([lk[1] for lk in links])
    GEc = link_block(gE, L, X, I, d)
    GAc = link_block(gA, L, X, I, d)
    w, Q = np.linalg.eigh(GAc)
    Sq = Q * np.sqrt(np.clip(w, 0, None))
    nu = np.sqrt(np.clip(np.linalg.eigvalsh(Sq.T @ GEc @ Sq), 0, None))
    return sym_entropy(nu)


